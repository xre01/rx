const fs=require('fs'),vm=require('vm'),assert=require('assert/strict'),memory=new Map(),events=[];
const ctx={window:{},localStorage:{getItem:k=>memory.get(k)||null,setItem:(k,v)=>memory.set(k,v)},dispatchEvent:e=>events.push(e.type),Event};
vm.createContext(ctx);vm.runInContext(fs.readFileSync('reading-xp.js','utf8'),ctx);
const {calculate,reconcile}=ctx.window.RexReadingXP,today='2026-10-18';
const article=(id,date=today)=>({id,kind:'article',writtenDate:date,body:'Note',logs:[]});
const book={id:'book',kind:'book',logs:[{date:today,note:'First'},{date:today,note:'Second'},{date:'2026-10-11',note:'Last week'}]};
assert.equal(calculate([book],today).total,6);
const articles=Array.from({length:11},(_,i)=>article('a'+i));
assert.equal(calculate(articles,today).total,30);
assert.equal(calculate(articles.slice(1),today).total,30);
assert.equal(calculate(articles.slice(2),today).total,27);
assert.equal(calculate([...articles,book],today).total,36);
assert.equal(calculate([article('a'),article('a')],today).total,3);
assert.equal(calculate([{...article('a'),deleted:true},article('future','2026-10-19'),article('invalid','2026-02-30')],today).total,0);
memory.set('arcane-sanctuary-v1',JSON.stringify({xp:100,ptePracticeXp:100,skill:{language:100}}));
reconcile([...articles,book],today);assert.equal(JSON.parse(memory.get('arcane-sanctuary-v1')).xp,136);
reconcile([...articles,book],today);assert.equal(JSON.parse(memory.get('arcane-sanctuary-v1')).xp,136);
reconcile(articles.slice(2),today);let state=JSON.parse(memory.get('arcane-sanctuary-v1'));assert.equal(state.xp,127);assert.equal(state.ptePracticeXp,100);assert.equal(state.skill.language,100);
reconcile([],today);assert.equal(JSON.parse(memory.get('arcane-sanctuary-v1')).xp,100);
console.log('PASS: book daily cap, article cap, deletion at/under cap, multiple dates, duplicate IDs, invalid/future dates, idempotent reconciliation, PTE isolation');
